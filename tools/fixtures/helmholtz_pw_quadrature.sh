#!/bin/sh
# Writes fmm-tables/src/helmholtz/plane_wave/hwts_iprec{1,2,3}.txt (nd-fmm-tables,
# Helmholtz CH6.1a) from FMM3D's quadratures of its Helmholtz exponential M2L
# (src/Helmholtz/hwts_3d_iprec{1,2,3}.txt of the FMM3D release that tools/fmm3d/build.sh
# pins, v2.1.0): per domain its index, quadrature type, rectangle in κ = k w, the error the
# file states and its nodes, then one line per node with the node and its weight.
#
# The files are NIST's: each output keeps their entire notice (everything above the first
# `ccccc` banner) and says when and how it was changed. FMM3D as a whole is Apache-2.0.
# The literals are FMM3D's digits with the exponent letter D written as e. Run from the
# repository root, on the directory that spikes/pw-quadrature/tools/fetch.sh unpacks:
#
#   tools/fixtures/helmholtz_pw_quadrature.sh "$(spikes/pw-quadrature/tools/fetch.sh)"
set -eu
src=${1:?usage: helmholtz_pw_quadrature.sh path/to/FMM3D/src/Helmholtz}
out=fmm-tables/src/helmholtz/plane_wave
mkdir -p "$out"
for p in 1 2 3; do
    f="$src/hwts_3d_iprec$p.txt"
    [ -f "$f" ] || { echo "helmholtz_pw_quadrature.sh: no $f" >&2; exit 2; }
    {
        echo "# Generated by tools/fixtures/helmholtz_pw_quadrature.sh from FMM3D v2.1.0,"
        echo "# src/Helmholtz/hwts_3d_iprec$p.txt; do not edit. That file carries this notice:"
        echo "#"
        awk '/^ccccc/ { exit } { sub(/^c ?/, ""); sub(/ +$/, ""); print ($0 == "" ? "#" : "# " $0) }' "$f"
        echo "# Changed on 2026-11-03 for the fmm repository (Helmholtz CH6.1a): rewritten"
        echo "# by tools/fixtures/helmholtz_pw_quadrature.sh into lines of values, the"
        echo "# Fortran statements dropped and the exponent letter D written as e; the values"
        echo "# and their digits unchanged."
        echo "#"
        echo "# domain <index> <iquadtype> <rk0r> <rk0i> <rk1r> <rk1i> <err> <n>, then n lines"
        echo "# <xs(k)> <ws(k)>."
        awk '
            function value(line) { sub(/^[^=]*= */, "", line); sub(/ +$/, "", line); gsub(/[dD]/, "e", line); return line }
            /^[cC]/ { next }
            /idomain *\.eq\./ { s = $0; gsub(/[^0-9]/, " ", s); split(s, a, " "); d = a[1] + 0; nx = 0; nw = 0; next }
            /^ *rk0r *=/ { r0r = value($0); next }
            /^ *rk0i *=/ { r0i = value($0); next }
            /^ *rk1r *=/ { r1r = value($0); next }
            /^ *rk1i *=/ { r1i = value($0); next }
            /^ *iquadtype *=/ { kind = value($0) + 0; next }
            /^ *n *=/ { n = value($0) + 0; next }
            /^ *err *=/ { err = value($0); next }
            /^ *xs\(/ { x[++nx] = value($0); next }
            /^ *ws\(/ { w[++nw] = value($0); next }
            /^ *endif/ {
                if (nx != n || nw != n) { printf "domain %d: %d nodes, %d weights, n = %d\n", d, nx, nw, n > "/dev/stderr"; exit 1 }
                printf "domain %d %d %s %s %s %s %s %d\n", d, kind, r0r, r0i, r1r, r1i, err, n
                for (k = 1; k <= n; k++) printf "%s %s\n", x[k], w[k]
            }
        ' "$f"
    } >"$out/hwts_iprec$p.txt"
done
wc -c "$out"/hwts_iprec*.txt
