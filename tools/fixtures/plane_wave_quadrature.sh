#!/bin/sh
# Writes fmm-tables/src/plane_wave/quadrature_data.rs (nd-fmm-tables, Phase 6 T13) from
# FMM3D's plane-wave quadrature tables (src/Laplace/lwtsexp_sep1.f of the FMM3D release
# that tools/fmm3d/build.sh pins, v2.1.0): for every number of λ nodes s = 2..39, the λ
# nodes and weights (`vwts`), the number of α nodes per λ (`numthetafour`), the number of
# Fourier modes per λ (`numthetahalf`) and the maximum error the file states.
#
# The file is NIST's (its notice is copied into the output); FMM3D as a whole is
# Apache-2.0. Moved here from the spike of Phase 6 T10 (spikes/plane-wave). Run from the
# repository root:
#
#   tools/fixtures/plane_wave_quadrature.sh $FMM3D_ROOT/build/default/FMM3D-2.1.0/src/Laplace/lwtsexp_sep1.f
set -eu
src=${1:?usage: plane_wave_quadrature.sh path/to/lwtsexp_sep1.f}
out=fmm-tables/src/plane_wave/quadrature_data.rs
{
    echo "// Generated by tools/fixtures/plane_wave_quadrature.sh from FMM3D v2.1.0,"
    echo "// src/Laplace/lwtsexp_sep1.f; do not edit. That file carries this notice:"
    echo "//"
    awk 'NR >= 1 && /^c/ { sub(/^c ?/, ""); print "// " $0 } /^ccccc/ { exit }' "$src" |
        sed -n '1,/RESULTS THEREOF/p;/^\/\/ CORRECTNESS/,/ protection within the United States\./p' |
        sed 's/ *$//'
    echo ""
    echo "/// One quadrature: λ nodes, weights, α nodes per λ, Fourier modes per λ, maximum error."
    echo "pub(crate) type Table = (&'static [f64], &'static [f64], &'static [usize], &'static [usize], f64);"
    echo ""
    echo "/// The quadratures of FMM3D for separation 1, by number of λ nodes s = 2..=39."
    echo "pub(crate) const TABLES: [Table; 38] = ["
    awk '
        function fnum(s) { gsub(/[dD]/, "e", s); return s }
        /subroutine vwts/ { sub_ = "vwts" }
        /subroutine numthetafour/ { sub_ = "four" }
        /subroutine numthetahalf/ { sub_ = "half" }
        /subroutine/ && !/vwts|numthetafour|numthetahalf/ { sub_ = "" }
        # The error column of the vwts comment.
        sub_ == "vwts" && /^c +[0-9]+ +0\.[0-9]+D[-+][0-9]+ *$/ {
            err[$2 + 0] = fnum($3)
        }
        sub_ == "vwts" && /if\(n\.eq\./ { match($0, /eq\. *[0-9]+/); cur = substr($0, RSTART + 3, RLENGTH - 3) + 0 }
        sub_ == "vwts" && /^[ \t]+x\( *[0-9]+\) *=/ { split($0, a, "="); x[cur] = x[cur] (x[cur] == "" ? "" : ", ") fnum(a[2]) }
        sub_ == "vwts" && /^[ \t]+w\( *[0-9]+\) *=/ { split($0, a, "="); w[cur] = w[cur] (w[cur] == "" ? "" : ", ") fnum(a[2]) }
        (sub_ == "four" || sub_ == "half") && /if\(nlams\.eq\./ { match($0, /eq\. *[0-9]+/); cur = substr($0, RSTART + 3, RLENGTH - 3) + 0 }
        sub_ == "four" && /numtets\( *[0-9]+\) *=/ { split($0, a, "="); v = a[2] + 0; four[cur] = four[cur] (four[cur] == "" ? "" : ", ") v }
        sub_ == "half" && /numtets\( *[0-9]+\) *=/ { split($0, a, "="); v = a[2] + 0; half[cur] = half[cur] (half[cur] == "" ? "" : ", ") v }
        END {
            for (n = 2; n <= 39; n++) {
                gsub(/ +/, "", x[n]); gsub(/ +/, "", w[n]); gsub(/,/, ", ", x[n]); gsub(/,/, ", ", w[n])
                printf "    // s = %d\n    (\n        &[%s],\n        &[%s],\n        &[%s],\n        &[%s],\n        %s,\n    ),\n", n, x[n], w[n], four[n], half[n], err[n]
            }
        }
    ' "$src"
    echo "];"
} >"$out"
echo "wrote $out; run cargo fmt --all"
