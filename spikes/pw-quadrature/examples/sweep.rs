//! The sweeps of S4 (SPIKE_REPORT.md), writing Markdown to `results/`:
//!
//! ```text
//! cargo run --release -p nd-fmm-spike-pw-quadrature --example sweep -- <FMM3D src/Helmholtz> [domains|rays|levels|all]
//! ```
//!
//! - `domains`: every FMM3D domain × precision at 9 points of its rectangle (corners,
//!   edge midpoints, centre): the λ sum's and the kernel's absolute errors on the region
//!   against the stated error, and the point-to-point chain at the centre;
//! - `rays`: real κ ∈ [0, 16π), imaginary κ ∈ i[0, 12π) and two damped rays, per
//!   precision: FMM3D's counts and errors, and the generator's at FMM3D's measured error;
//! - `levels`: the κ_l = k w_l of the levels of the reference trees, which domain and
//!   precision serve each ε, with what error, and which fall outside the tables or are
//!   pruned (proposal §5.5 with θ_D = 1).

use nd_fmm_spike_pw_quadrature::C;
use nd_fmm_spike_pw_quadrature::fmm3d::{self, DOMAINS, NX, NY, Tables};
use nd_fmm_spike_pw_quadrature::generator;
use nd_fmm_spike_pw_quadrature::quadrature::Quadrature;
use nd_fmm_spike_pw_quadrature::region::{Grid, Pairs};
use rayon::prelude::*;
use std::fmt::Write as _;
use std::path::Path;

fn main() {
    let mut args = std::env::args().skip(1);
    let dir = args
        .next()
        .expect("usage: sweep <FMM3D src/Helmholtz> [domains|rays|levels|all]");
    let what = args.next().unwrap_or_else(|| "all".into());
    let tables = Tables::load(Path::new(&dir));
    let out = Path::new(env!("CARGO_MANIFEST_DIR")).join("results");
    std::fs::create_dir_all(&out).unwrap();
    let write = |name: &str, text: String| {
        std::fs::write(out.join(name), text).unwrap();
        eprintln!("wrote results/{name}");
    };
    if what == "domains" || what == "all" {
        write("domains.md", domains(&tables));
    }
    if what == "rays" || what == "all" {
        write("rays.md", rays(&tables));
    }
    if what == "levels" || what == "all" {
        write("levels.md", levels(&tables));
    }
}

/// The 9 points of a domain's rectangle: corners, edge midpoints, centre; the upper
/// edges pulled in by 10⁻⁹ (relative), which the lookup assigns to the next domain.
fn nine(domain: usize) -> Vec<C> {
    let (lo, hi) = fmm3d::rectangle(domain);
    let top = |a: f64, b: f64| b - 1e-9 * (b - a).max(b.abs());
    let re = [lo.re, 0.5 * (lo.re + hi.re), top(lo.re, hi.re)];
    let im = [lo.im, 0.5 * (lo.im + hi.im), top(lo.im, hi.im)];
    im.iter()
        .flat_map(|&y| re.iter().map(move |&x| C::new(x, y)))
        .collect()
}

#[derive(Clone, Copy, Default)]
struct DomainRow {
    stated: f64,
    lambda: f64,
    kernel: f64,
    kernel_rel: f64,
    chain: f64,
    nodes: usize,
    terms: usize,
    fourier: usize,
}

fn domains(tables: &Tables) -> String {
    let grid = Grid::region();
    let pairs = Pairs::up(4);
    let mut s = String::new();
    writeln!(s, "# S4: FMM3D's domains\n").unwrap();
    writeln!(
        s,
        "Generated by `examples/sweep.rs domains`. Per precision (`iprec`) and domain, the \
         worst over 9 points of the rectangle (corners with the upper edges pulled in by \
         10⁻⁹, edge midpoints, centre) of: the λ sum's absolute error on the region (α \
         resolved), the kernel's absolute error with FMM3D's α counts, the same relative \
         to the region's largest |G|, and at the centre the point-to-point chain with \
         FMM3D's Fourier counts (sources: the box's corners, its centre and 4 seeded \
         points; targets: the 15 × 15 × 5 tensor of the up direction's target boxes). \
         Absolute errors are in box widths (G = e^{{iκ|u|}}/|u|).\n"
    )
    .unwrap();
    for (p, precision) in tables.precisions.iter().enumerate() {
        let rows: Vec<(usize, DomainRow)> = (1..=DOMAINS)
            .into_par_iter()
            .map(|d| {
                let dom = &precision[&d];
                let mut row = DomainRow {
                    stated: dom.stated_error,
                    nodes: dom.len(),
                    ..Default::default()
                };
                for kw in nine(d) {
                    assert_eq!(fmm3d::domain_of(kw), Some(d), "{kw} not in {d}");
                    let q = Quadrature::from_fmm3d(dom, kw);
                    let l = q.lambda_errors(&grid);
                    let e = q.kernel_errors(&grid);
                    row.lambda = row.lambda.max(l.absolute);
                    row.kernel = row.kernel.max(e.absolute);
                    row.kernel_rel = row.kernel_rel.max(e.relative_to_max);
                    row.terms = q.physical_terms();
                    row.fourier = q.fourier_terms();
                }
                let (lo, hi) = fmm3d::rectangle(d);
                let q = Quadrature::from_fmm3d(dom, 0.5 * (lo + hi));
                row.chain = q.chain_errors(&pairs, true).absolute;
                (d, row)
            })
            .collect();
        let errmax = fmm3d::errmax(p);
        let worst = |f: &dyn Fn(&DomainRow) -> f64| {
            rows.iter()
                .map(|(d, r)| (f(r), *d))
                .fold((0.0, 0), |a, b| if b.0 > a.0 { b } else { a })
        };
        let (wl, dl) = worst(&|r| r.lambda / r.stated);
        let (wk, dk) = worst(&|r| r.kernel / r.stated);
        let (ak, ak_d) = worst(&|r| r.kernel);
        let (ac, ac_d) = worst(&|r| r.chain);
        let (ar, ar_d) = worst(&|r| r.kernel_rel);
        let max_stated = rows.iter().map(|(_, r)| r.stated).fold(0.0, f64::max);
        writeln!(s, "## iprec {p} (eps class: {})\n", eps_class(p)).unwrap();
        writeln!(
            s,
            "| quantity | worst | domain (its rectangle) |\n| --- | --- | --- |"
        )
        .unwrap();
        let rect = |d: usize| {
            let (lo, hi) = fmm3d::rectangle(d);
            format!(
                "{d} ({:.3}..{:.3} + i {:.3}..{:.3})",
                lo.re, hi.re, lo.im, hi.im
            )
        };
        writeln!(s, "| largest stated error | {max_stated:.2e} | – |").unwrap();
        writeln!(s, "| `errmax` of `hwts3e` | {errmax:.0e} | – |").unwrap();
        writeln!(s, "| λ sum / stated | {wl:.2} | {} |", rect(dl)).unwrap();
        writeln!(s, "| kernel / stated | {wk:.2} | {} |", rect(dk)).unwrap();
        writeln!(s, "| kernel, absolute | {ak:.2e} | {} |", rect(ak_d)).unwrap();
        writeln!(
            s,
            "| kernel, relative to max \\|G\\| | {ar:.2e} | {} |",
            rect(ar_d)
        )
        .unwrap();
        writeln!(
            s,
            "| chain at the centre, absolute | {ac:.2e} | {} |\n",
            rect(ac_d)
        )
        .unwrap();
        writeln!(
            s,
            "log₁₀ of the kernel's absolute error per domain (rows Im κ, columns Re κ by \
             their lower breakpoints), then the nodes s and Σ Nₖ:\n"
        )
        .unwrap();
        s += &map(&rows, &|r| format!("{:.1}", r.kernel.log10()));
        s += "\n";
        s += &map(&rows, &|r| format!("{}", r.nodes));
        s += "\n";
        s += &map(&rows, &|r| format!("{}", r.terms));
        s += "\n";
    }
    s
}

fn eps_class(p: usize) -> &'static str {
    [
        "eps ≥ 5e-3",
        "5e-4 ≤ eps < 5e-3",
        "5e-7 ≤ eps < 5e-4",
        "5e-10 ≤ eps < 5e-7",
        "eps < 5e-10",
    ][p]
}

fn map(rows: &[(usize, DomainRow)], cell: &dyn Fn(&DomainRow) -> String) -> String {
    let mut s = String::from("| Im \\ Re |");
    for ix in 0..NX {
        write!(s, " {} |", short(fmm3d::RE_BREAKS[ix])).unwrap();
    }
    s += "\n|---|";
    s += &"---|".repeat(NX);
    s += "\n";
    for iy in 0..NY {
        write!(s, "| {} |", short(fmm3d::IM_BREAKS[iy])).unwrap();
        for ix in 0..NX {
            let d = ix + iy * NX + 1;
            write!(s, " {} |", cell(&rows[d - 1].1)).unwrap();
        }
        s += "\n";
    }
    s
}

/// A breakpoint as written: multiples of π as "kπ", the rest as decimals.
fn short(v: f64) -> String {
    let k = v / core::f64::consts::PI;
    if v >= 1.5 && (k - k.round()).abs() < 1e-9 {
        format!("{}π", k.round())
    } else if (k - 0.5).abs() < 1e-9 {
        "π/2".into()
    } else {
        format!("{v}")
    }
}

fn rays(tables: &Tables) -> String {
    let grid = Grid::region();
    let pairs = Pairs::up(4);
    let pi = core::f64::consts::PI;
    let rays: Vec<(&str, Vec<C>)> = vec![
        (
            "real κ",
            (0..32)
                .map(|i| C::new(0.25 + i as f64 * 0.5 * pi, 0.0))
                .collect(),
        ),
        (
            "imaginary κ (Yukawa)",
            (0..24)
                .map(|i| C::new(0.0, 0.25 + i as f64 * 0.5 * pi))
                .collect(),
        ),
        (
            "damped κ (1 + 0.05i)",
            (0..32)
                .map(|i| C::new(1.0, 0.05) * (0.25 + i as f64 * 0.5 * pi))
                .collect(),
        ),
        (
            "damped κ (1 + 0.5i)",
            (0..24)
                .map(|i| C::new(1.0, 0.5) * (0.25 + i as f64 * 0.5 * pi))
                .collect(),
        ),
    ];
    let mut s = String::new();
    writeln!(s, "# S4: rays in κ = k w\n").unwrap();
    writeln!(
        s,
        "Generated by `examples/sweep.rs rays`. Per κ and precision: FMM3D's quadrature \
         (nodes s, Σ Nₖ, Σ (2Fₖ + 1); the kernel's absolute error on the region with its α \
         counts; the chain's with its Fourier counts), and the generator run at ε = \
         FMM3D's measured kernel error, but at least 1 % of the precision's `errmax` and 10⁻¹³ (where \
         |G| ≤ e^{{−Im κ}} is far below it FMM3D needs one node): its s, Σ Nₖ, \
         Σ (2Fₖ + 1), kernel and chain errors; not at iprec 4, beyond D1's ε. The ratio is \
         the generator's Σ Nₖ over FMM3D's.\n"
    )
    .unwrap();
    for (name, ks) in rays {
        writeln!(s, "## {name}\n").unwrap();
        for p in 1..=4 {
            writeln!(s, "### iprec {p}\n").unwrap();
            writeln!(
                s,
                "| κ | FMM3D s | Σ N | Σ (2F+1) | kernel | chain | gen. s | Σ N | Σ (2F+1) | kernel | chain | ratio |\n\
                 | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"
            )
            .unwrap();
            let lines: Vec<String> = ks
                .par_iter()
                .map(|&kw| {
                    let Some(dom) = tables.lookup(p, kw) else {
                        return format!("| {kw:.3} | outside the tables | | | | | | | | | | |");
                    };
                    let q = Quadrature::from_fmm3d(dom, kw);
                    let e = q.kernel_errors(&grid).absolute;
                    let c = q.chain_errors(&pairs, true).absolute;
                    if p == 4 {
                        // The generator is not run at iprec 4: its targets near 10⁻¹³
                        // take minutes per κ, and D1's ε (10⁻³ to 10⁻⁸) needs iprec ≤ 3.
                        return format!(
                            "| {kw:.3} | {} | {} | {} | {e:.1e} | {c:.1e} | – | – | – | – | – | – |",
                            q.nodes(),
                            q.physical_terms(),
                            q.fourier_terms()
                        );
                    }
                    let target = e.max(fmm3d::errmax(p) / 100.0).max(generator::FLOOR);
                    let g = generator::generate(kw, target);
                    let ge = g.kernel_errors(&grid).absolute;
                    let gc = g.chain_errors(&pairs, true).absolute;
                    format!(
                        "| {kw:.3} | {} | {} | {} | {e:.1e} | {c:.1e} | {} | {} | {} | {ge:.1e} | {gc:.1e} | {:.2} |",
                        q.nodes(),
                        q.physical_terms(),
                        q.fourier_terms(),
                        g.nodes(),
                        g.physical_terms(),
                        g.fourier_terms(),
                        g.physical_terms() as f64 / q.physical_terms() as f64
                    )
                })
                .collect();
            for l in lines {
                writeln!(s, "{l}").unwrap();
            }
            s += "\n";
            eprintln!("rays: {name}, iprec {p} done");
        }
    }
    s
}

fn levels(tables: &Tables) -> String {
    let grid = Grid::region();
    let pairs = Pairs::up(4);
    let cases: Vec<(&str, C)> = vec![
        ("real", C::new(10.0, 0.0)),
        ("real", C::new(100.0, 0.0)),
        ("real", C::new(500.0, 0.0)),
        ("Yukawa", C::new(0.0, 10.0)),
        ("Yukawa", C::new(0.0, 100.0)),
        ("Yukawa", C::new(0.0, 500.0)),
        ("damped", C::new(100.0, 5.0)),
        ("damped", C::new(500.0, 25.0)),
    ];
    let mut s = String::new();
    writeln!(s, "# S4: the levels of the reference trees\n").unwrap();
    writeln!(
        s,
        "Generated by `examples/sweep.rs levels`. Root side D = 1, so κ_l = k w_l = kD / 2^l. \
         Levels 2 to 8 (deeper levels have smaller |κ_l|, inside domain 1's row). Per ε of \
         D1's range, `hwts3e`'s precision (`precision_of`), the domain, the kernel's \
         absolute error on the region and Σ Nₖ, and the generator at the same ε: its Σ Nₖ, \
         its kernel's absolute error and its chain's (sources: the box's corners, its centre \
         and 4 seeded points). \"pruned\": proposal §5.5's test e^{{−Im k (w_l − w_leaf)}} w_leaf / w_l ≤ ε \
         with θ_D = 1 and w_leaf = 1 λ (c_leaf = 1, D11) for Re k > 0, else the level-8 \
         width; FMM3D's own cut, e^{{−Im κ_l}}/w_l < ε (w_l = D / 2^l), is in the last column.\n"
    )
    .unwrap();
    writeln!(
        s,
        "| case | kD | level | κ_l | ε | iprec | domain | kernel | Σ N | gen. Σ N | gen. kernel | gen. chain | FMM3D cut |\n\
         | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"
    )
    .unwrap();
    let mut jobs = Vec::new();
    for &(name, k) in &cases {
        for l in 2..=8u32 {
            for eps in [1e-3, 1e-6, 1e-8] {
                jobs.push((name, k, l, eps));
            }
        }
    }
    let lines: Vec<String> = jobs
        .par_iter()
        .map(|&(name, k, l, eps)| {
            let w = 1.0 / 2f64.powi(l as i32);
            let kw = k * w;
            let w_leaf = if k.re > 0.0 {
                (core::f64::consts::TAU / k.re).min(w)
            } else {
                1.0 / 256.0
            };
            let pruned = (-k.im * (w - w_leaf)).exp() * w_leaf / w <= eps;
            let fmm3d_cut = (-kw.im).exp() / w < eps;
            let p = fmm3d::precision_of(eps);
            let head = format!("| {name} | {k} | {l} | {kw:.3} | {eps:.0e} | {p} |");
            let cut = if fmm3d_cut { "cut" } else { "–" };
            if pruned {
                return format!("{head} pruned | | | | | | {cut} |");
            }
            let Some(dom) = tables.lookup(p, kw) else {
                let g = generator::generate(kw, eps);
                return format!(
                    "{head} outside | | | {} | {:.1e} | {:.1e} | {cut} |",
                    g.physical_terms(),
                    g.kernel_errors(&grid).absolute,
                    g.chain_errors(&pairs, true).absolute
                );
            };
            let q = Quadrature::from_fmm3d(dom, kw);
            let e = q.kernel_errors(&grid).absolute;
            let g = generator::generate(kw, eps);
            format!(
                "{head} {} | {e:.1e} | {} | {} | {:.1e} | {:.1e} | {cut} |",
                dom.index,
                q.physical_terms(),
                g.physical_terms(),
                g.kernel_errors(&grid).absolute,
                g.chain_errors(&pairs, true).absolute
            )
        })
        .collect();
    for l in lines {
        writeln!(s, "{l}").unwrap();
    }
    s
}
